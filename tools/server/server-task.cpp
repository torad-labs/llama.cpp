void server_prompt_cache::insert_state(server_prompt_cache_state && state) {
    state.freeze_size();
    states.push_back(std::move(state));
    total_bytes += states.back().cached_size;
    total_tokens += states.back().prompt.n_tokens();
    ++revision;
}

std::list<server_prompt_cache_state>::iterator server_prompt_cache::erase_state(
        std::list<server_prompt_cache_state>::iterator it) {
    GGML_ASSERT(total_bytes >= it->cached_size && total_tokens >= (size_t) it->prompt.n_tokens());
    total_bytes -= it->cached_size;
    total_tokens -= it->prompt.n_tokens();
    ++revision;
    return states.erase(it);
}

size_t server_prompt_cache::size() const {
    return total_bytes;
}

size_t server_prompt_cache::n_tokens() const {
    return total_tokens;
}

const char * server_prompt_cache_result_name(server_prompt_cache_result result) {
    switch (result) {
        case server_prompt_cache_result::saved:          return "saved";
        case server_prompt_cache_result::already_cached: return "already_cached";
        case server_prompt_cache_result::saving:         return "saving";
        case server_prompt_cache_result::empty:          return "empty";
        case server_prompt_cache_result::too_large:      return "too_large";
        case server_prompt_cache_result::no_space:       return "no_space";
        case server_prompt_cache_result::failed:         return "failed";
    }
    return "unknown";
}

server_prompt_cache_result server_prompt_cache::save_idle(const server_prompt & prompt,
        llama_context * ctx_tgt, llama_context * ctx_dft, common_speculative * spec, int32_t id_slot,
        server_prompt_cache_refusal & refusal) {
    if (refusal.cache == this && refusal.revision == revision &&
            refusal.limit_size == limit_size && refusal.limit_tokens == limit_tokens &&
            (refusal.result == server_prompt_cache_result::too_large || refusal.result == server_prompt_cache_result::no_space)) {
        SRV_TRC("cache_save reason=unchanged_refusal slot=%d result=%s\n", id_slot, server_prompt_cache_result_name(refusal.result));
        return refusal.result;
    }

    const auto result = save(prompt, ctx_tgt, ctx_dft, spec, id_slot, nullptr, false);
    refusal = { this, revision, limit_size, limit_tokens, result };
    return result;
}

// LLAMA_STATE_SAVE_ASYNC=1: a slot's state saved for a task that can come back for the slot returns once its layout is written, and a thread of the context copies its rows to the snapshot while the other slots decode (llama_state_seq_get_data_async)
static bool state_save_async() {
    static const bool async = ggml_env_switch("LLAMA_STATE_SAVE_ASYNC");
    return async;
}

server_prompt_cache_result server_prompt_cache::save(const server_prompt & prompt,
        llama_context * ctx_tgt, llama_context * ctx_dft, common_speculative * spec, int32_t id_slot,
        const server_prompt_cache_state * protect, bool allow_evict, bool async) {
    if (prompt.tokens.empty()) {
        return server_prompt_cache_result::empty;
    }
    async = async && state_save_async();

    // A save of the slot that still copies. The slot takes no part in a step meanwhile, so it is this prompt's: a caller
    // that can come back does, and another waits for the copy here and finds it cached below.
    reap(false, protect);
    if (const auto it = saving_refused.find(id_slot); it != saving_refused.end()) {
        const auto refused = it->second;
        saving_refused.erase(it);
        if (async && refused.first == prompt.tokens.size()) {
            return refused.second;
        }
    }
    for (const auto & cur : saving) {
        if (cur.id_slot == id_slot && cur.ctx_tgt == ctx_tgt) {
            if (async && cur.state.prompt.tokens.size() == prompt.tokens.size()) {
                return server_prompt_cache_result::saving;
            }
            llama_state_seq_async_wait(cur.ctx_tgt, id_slot);
            if (cur.ctx_dft) {
                llama_state_seq_async_wait(cur.ctx_dft, id_slot);
            }
            reap(false, protect);
            break;
        }
    }
    // the snapshots other slots' saves still copy to
    size_t size_saving = 0;
    for (const auto & cur : saving) {
        size_saving += cur.state.size();
    }

    const llama_pos pos_min = llama_memory_seq_pos_min(llama_get_memory(ctx_tgt), id_slot);
    // A longer recurrent snapshot need not be able to roll back to this prompt.
    // Only deduplicate an exact state with at least the same checkpoint coverage.
    for (const auto & state : states) {
        if (state.data->main.empty() || (ctx_dft && state.data->drft.empty()) ||
                state.prompt.tokens.size() != prompt.tokens.size() ||
                state.prompt.tokens.get_common_prefix(prompt.tokens) != prompt.tokens.size() || state.pos_min > pos_min) {
            continue;
        }
        bool covered = true;
        for (const auto & checkpoint : prompt.checkpoints) {
            covered = covered && std::any_of(state.prompt.checkpoints.begin(), state.prompt.checkpoints.end(),
                [&](const common_prompt_checkpoint & saved) {
                    return saved.n_tokens == checkpoint.n_tokens && saved.pos_min == checkpoint.pos_min &&
                           saved.pos_max == checkpoint.pos_max;
                });
        }
        if (covered) {
            return server_prompt_cache_result::already_cached;
        }
    }

    try {
        // Token-only rejection does not need either model's serialized state size.
        if (!allow_evict && limit_size == 0 && limit_tokens > 0 &&
                ((size_t) prompt.n_tokens() > limit_tokens || n_tokens() > limit_tokens - prompt.n_tokens())) {
            return server_prompt_cache_result::no_space;
        }
        if (protect && limit_size == 0 && limit_tokens > 0 &&
                (size_t) protect->prompt.n_tokens() + (size_t) prompt.n_tokens() > limit_tokens) {
            SRV_TRC("cache_save reason=no_space slot=%d tokens=%d protected=%d limit=%zu\n",
                    id_slot, prompt.n_tokens(), protect->prompt.n_tokens(), limit_tokens);
            return server_prompt_cache_result::no_space;
        }

        server_prompt_cache_state pending;
        pending.pos_min = pos_min;
        const size_t size_tgt = llama_state_seq_get_size_ext(ctx_tgt, id_slot, LLAMA_STATE_SEQ_FLAGS_NONE);
        const size_t size_dft = ctx_dft ? llama_state_seq_get_size_ext(ctx_dft, id_slot, LLAMA_STATE_SEQ_FLAGS_NONE) : 0;
        // Serialize the small implementation-specific row before admission, so it
        // is included in the budget rather than appended to an already full cache.
        common_speculative_get_state(spec, id_slot, pending.data->spec);
        size_t size_new = pending.data->spec.size();
        const auto add_size = [&](size_t value) {
            if (value > SIZE_MAX - size_new) {
                return false;
            }
            size_new += value;
            return true;
        };
        bool fits = add_size(size_tgt) && add_size(size_dft);
        for (const auto & checkpoint : prompt.checkpoints) {
            fits = fits && add_size(checkpoint.size());
        }
        if (!fits || (limit_size > 0 && size_new > limit_size)) {
            SRV_WRN("cache_save reason=too_large: prompt state exceeds cache size limit (bytes=%zu, limit=%zu)\n",
                    size_new, limit_size);
            return server_prompt_cache_result::too_large;
        }
        if (size_tgt == 0 || pos_min < 0 || (ctx_dft && size_dft == 0)) {
            SRV_WRN("cache_save reason=invalid_state slot=%d\n", id_slot);
            return server_prompt_cache_result::failed;
        }

        if (limit_size > 0) {
            const size_t retained = protect ? protect->size() : 0;
            // the snapshots other slots' saves still copy to are held too, and join the cache when their copies are done
            if (retained > limit_size || (protect && size_new > limit_size - retained) ||
                    size_saving > limit_size - size_new ||
                    (!allow_evict && size() + size_saving > limit_size - size_new)) {
                SRV_TRC("cache_save reason=no_space slot=%d bytes=%zu protected=%zu saving=%zu limit=%zu\n",
                        id_slot, size_new, retained, size_saving, limit_size);
                return server_prompt_cache_result::no_space;
            }
            // Evictions precede allocation to keep snapshot storage bounded.
            // The selected incoming state must survive even when saving fails.
            for (auto it = states.begin(); size() + size_saving > limit_size - size_new && it != states.end();) {
                if (&*it == protect) {
                    ++it;
                    continue;
                }
                SRV_WRN("cache_evict reason=admission tokens=%d bytes=%zu\n", it->prompt.n_tokens(), it->size());
                it = erase_state(it);
            }
        }

        pending.prompt = prompt.clone();
        pending.data->main.resize(size_tgt);
        pending.data->drft.resize(size_dft);
        if (async) {
            const int64_t t_start = ggml_time_us();
            const bool ok = llama_state_seq_get_data_async(ctx_tgt, pending.data->main.data(), size_tgt, id_slot,
                        LLAMA_STATE_SEQ_FLAGS_NONE) == size_tgt &&
                    (!ctx_dft || llama_state_seq_get_data_async(ctx_dft, pending.data->drft.data(), size_dft, id_slot,
                        LLAMA_STATE_SEQ_FLAGS_NONE) == size_dft);
            if (!ok) {
                // a copy that did start writes to the snapshot freed here
                llama_state_seq_async_wait(ctx_tgt, id_slot);
                if (ctx_dft) {
                    llama_state_seq_async_wait(ctx_dft, id_slot);
                }
                SRV_WRN("cache_save reason=serialization_failed slot=%d bytes=%zu\n", id_slot, size_new);
                return server_prompt_cache_result::failed;
            }
            SRV_TRC("cache_save reason=saving slot=%d tokens=%d bytes=%zu\n", id_slot, prompt.n_tokens(), size_new);
            saving.push_back({ ctx_tgt, ctx_dft, id_slot, t_start, ggml_time_us() - t_start, std::move(pending) });
            return server_prompt_cache_result::saving;
        }
        if (llama_state_seq_get_data_ext(ctx_tgt, pending.data->main.data(), size_tgt, id_slot,
                    LLAMA_STATE_SEQ_FLAGS_NONE) != size_tgt ||
                (ctx_dft && llama_state_seq_get_data_ext(ctx_dft, pending.data->drft.data(), size_dft, id_slot,
                    LLAMA_STATE_SEQ_FLAGS_NONE) != size_dft)) {
            SRV_WRN("cache_save reason=serialization_failed slot=%d bytes=%zu\n", id_slot, size_new);
            return server_prompt_cache_result::failed;
        }

        // Publish only after both model states and the drafter state are complete.
        return publish(std::move(pending), protect, id_slot);
    } catch (const std::exception & e) {
        SRV_ERR("cache_save reason=exception slot=%d error=%s\n", id_slot, e.what());
        return server_prompt_cache_result::failed;
    }
}

server_prompt_cache_result server_prompt_cache::publish(server_prompt_cache_state && state,
        const server_prompt_cache_state * protect, int32_t id_slot) {
    insert_state(std::move(state));
    const auto * saved = &states.back();
    const auto & tokens = saved->prompt.tokens;
    for (auto it = states.begin(); &*it != saved;) {
        if (&*it != protect && it->prompt.tokens.size() == tokens.size() &&
                it->prompt.tokens.get_common_prefix(tokens) == tokens.size()) {
            it = erase_state(it);
        } else {
            ++it;
        }
    }
    const int    n_tokens = saved->prompt.n_tokens();
    const size_t n_bytes  = saved->size();
    update(protect);
    if (std::none_of(states.begin(), states.end(),
            [&](const server_prompt_cache_state & cur) { return &cur == saved; })) {
        return server_prompt_cache_result::no_space;
    }
    SRV_TRC("cache_save reason=saved slot=%d tokens=%d bytes=%zu\n", id_slot, n_tokens, n_bytes);
    return server_prompt_cache_result::saved;
}

size_t server_prompt_cache::reusable_prefix(const server_prompt & prompt, const server_tokens & tokens_new,
        llama_pos pos_min, int32_t n_swa, std::optional<size_t> lcp) {
    size_t reused = lcp.value_or(prompt.tokens.get_common_prefix(tokens_new));
    if (reused == 0 || pos_min < 0) {
        return 0;
    }
    auto pos_next = prompt.tokens.pos_next(reused);
    const auto pos_min_thold = std::max(0, pos_next - n_swa - (reused < tokens_new.size() ? 0 : 1));
    if (pos_min >= pos_min_thold) {
        // Keep this aligned with checkpoint fallback during prompt preparation.
        const auto checkpoint = std::find_if(prompt.checkpoints.rbegin(), prompt.checkpoints.rend(),
            [&](const common_prompt_checkpoint & cur) {
                return cur.pos_max <= pos_next && (cur.pos_min < pos_min_thold || cur.pos_min == 0);
            });
        if (checkpoint == prompt.checkpoints.rend()) {
            return 0;
        }
        pos_next = std::min(pos_next, std::max(checkpoint->pos_min + 1, checkpoint->pos_max));
        reused = std::min(prompt.tokens.size_up_to_pos(pos_next), (size_t) checkpoint->n_tokens);
    }
    // Each request must still evaluate at least one token for logits.
    return reused == tokens_new.size() ? reused - 1 : reused;
}

server_prompt_cache_state * server_prompt_cache::find_best(const server_prompt & prompt,
        const server_tokens & tokens_new, llama_pos pos_min, int32_t n_swa, std::optional<size_t> resident_reuse) {
    size_t best_reuse = resident_reuse ? *resident_reuse : reusable_prefix(prompt, tokens_new, pos_min, n_swa);
    server_prompt_cache_state * best = nullptr;
    for (auto & state : states) {
        if (state.data->main.empty()) {
            continue;
        }
        const size_t lcp = state.prompt.tokens.get_common_prefix(tokens_new);
        const size_t reused = reusable_prefix(state.prompt, tokens_new, state.pos_min, n_swa, lcp);
        SRV_TRC("cache_candidate tokens=%d lcp=%zu reusable=%zu bytes=%zu\n", state.prompt.n_tokens(),
                lcp, reused, state.size());
        // Restoring a snapshot to keep under a quarter of it costs a transfer for little saved computation, and the
        // slot then cuts the rest: such a candidate is passed over (main's "don't trash large prompts").
        if (4 * reused < (size_t) state.prompt.n_tokens()) {
            continue;
        }
        // Prefer saved computation; avoid a transfer on a tie with resident KV.
        if (reused > best_reuse || (best && reused == best_reuse && state.size() < best->size())) {
            best_reuse = reused;
            best = &state;
        }
    }
    return best;
}

// LLAMA_STATE_RESTORE_ASYNC=1: a snapshot restored into a slot returns once its cells are placed, and a thread of the context copies its rows while the other slots decode (llama_state_seq_set_data_async)
static bool state_restore_async() {
    static const bool async = ggml_env_switch("LLAMA_STATE_RESTORE_ASYNC");
    return async;
}

bool server_prompt_cache::load(server_prompt & prompt, server_prompt_cache_state * selected,
        llama_context * ctx_tgt, llama_context * ctx_dft, common_speculative * spec, int32_t id_slot, bool consume) {
    reap(false, selected);
    if (!selected) {
        return true;
    }
    const auto it = std::find_if(states.begin(), states.end(),
        [&](const server_prompt_cache_state & state) { return &state == selected; });
    GGML_ASSERT(it != states.end());

    // Do not consume any bytes until all restores succeed. A failure leaves a
    // complete snapshot available for retry, never a metadata-only cache hit.
    const std::shared_ptr<const server_prompt_data> data = it->data;
    const bool async = state_restore_async();
    const auto set_data = [&](llama_context * ctx, const server_state_bytes & bytes) {
        return async ?
            llama_state_seq_set_data_async(ctx, bytes.data(), bytes.size(), id_slot, LLAMA_STATE_SEQ_FLAGS_NONE) :
            llama_state_seq_set_data_ext  (ctx, bytes.data(), bytes.size(), id_slot, LLAMA_STATE_SEQ_FLAGS_NONE);
    };
    bool restored = false;
    try {
        restored = !data->main.empty() && (!ctx_dft || !data->drft.empty()) &&
                set_data(ctx_tgt, data->main) == data->main.size();
        if (restored && !data->drft.empty()) {
            restored = ctx_dft && set_data(ctx_dft, data->drft) == data->drft.size();
        }
        if (restored) {
            common_speculative_set_state(spec, id_slot, data->spec);
        }
    } catch (const std::exception & e) {
        SRV_ERR("cache_restore reason=exception slot=%d error=%s\n", id_slot, e.what());
        restored = false;
    }
    if (!restored) {
        // Both sequences may have been partially overwritten, including when the
        // target loader itself failed. Clear them together before a fresh prefill.
        // A target restore that still copies writes to the cells removed here.
        llama_state_seq_async_wait(ctx_tgt, id_slot);
        llama_memory_seq_rm(llama_get_memory(ctx_tgt), id_slot, -1, -1);
        if (ctx_dft) {
            llama_state_seq_async_wait(ctx_dft, id_slot);
            llama_memory_seq_rm(llama_get_memory(ctx_dft), id_slot, -1, -1);
        }
        common_speculative_set_state(spec, id_slot, {});
        prompt.clear();
        SRV_WRN("cache_restore reason=restore_failed slot=%d bytes=%zu retained=1\n", id_slot, it->size());
        return false;
    }
    if (async) {
        restoring.push_back({ ctx_tgt, ctx_dft, id_slot, data });
    }
    SRV_TRC("cache_restore reason=restored slot=%d tokens=%d bytes=%zu consumed=%d async=%d\n", id_slot, it->prompt.n_tokens(),
            it->size(), consume, async);
    if (consume) {
        GGML_ASSERT(total_bytes >= it->cached_size && total_tokens >= (size_t) it->prompt.n_tokens());
        total_bytes -= it->cached_size;
        total_tokens -= it->prompt.n_tokens();
        prompt = std::move(it->prompt);
        states.erase(it);
        ++revision;
    } else {
        // The slot keeps only the shared prefix; the conversation the snapshot belongs to stays recoverable.
        prompt = it->prompt.clone();
    }
    return true;
}

void server_prompt_cache::reap(bool wait, const server_prompt_cache_state * protect) {
    const auto done = [wait](const llama_context * ctx_tgt, const llama_context * ctx_dft, int32_t id_slot) {
        if (wait) {
            llama_state_seq_async_wait(ctx_tgt, id_slot);
            if (ctx_dft) {
                llama_state_seq_async_wait(ctx_dft, id_slot);
            }
        }
        return !llama_state_seq_async_pending(ctx_tgt, id_slot) &&
            !(ctx_dft && llama_state_seq_async_pending(ctx_dft, id_slot));
    };
    for (auto it = restoring.begin(); it != restoring.end();) {
        it = done(it->ctx_tgt, it->ctx_dft, it->id_slot) ? restoring.erase(it) : std::next(it);
    }
    for (auto it = saving.begin(); it != saving.end();) {
        if (!done(it->ctx_tgt, it->ctx_dft, it->id_slot)) {
            ++it;
            continue;
        }
        const int32_t id_slot = it->id_slot;
        const double  t_copy  = (ggml_time_us() - it->t_start) / 1000.0;
        const double  t_here  = it->t_placed / 1000.0;
        // the room for this one was made before its copy. The state its save protected may have left the cache since: the one kept here is the one this call's caller holds
        const size_t n_tokens = it->state.prompt.tokens.size();
        const auto result = publish(std::move(it->state), protect, id_slot);
        if (result != server_prompt_cache_result::saved) {
            saving_refused[id_slot] = { n_tokens, result };
        }
        SRV_INF("slot %d saved to the prompt cache %.2f ms after the save started, %.2f ms of them on the server's thread, result=%s\n",
                id_slot, t_copy, t_here, server_prompt_cache_result_name(result));
        saved = true;
        it = saving.erase(it);
    }
}

void server_prompt_cache::update(const server_prompt_cache_state * protect) {
    if (limit_size > 0) {
        for (auto it = states.begin(); size() > limit_size && it != states.end();) {
            if (&*it == protect) {
                ++it;
                continue;
            }
            SRV_WRN("cache_evict reason=byte_limit tokens=%d bytes=%zu\n", it->prompt.n_tokens(), it->size());
            it = erase_state(it);
        }
    }

    // The token cap is a fallback for an unlimited byte budget. With a byte
    // budget, snapshots that fit must stay: a bytes/token estimate can round
    // down and evict an exact-fit entry even during a non-evicting save.
    if (limit_size == 0 && limit_tokens > 0) {
        for (auto it = states.begin(); n_tokens() > limit_tokens && it != states.end();) {
            if (&*it == protect) {
                ++it;
                continue;
            }
            SRV_WRN("cache_evict reason=token_limit tokens=%d bytes=%zu limit=%zu\n",
                    it->prompt.n_tokens(), it->size(), limit_tokens);
            it = erase_state(it);
        }
    }

    SRV_TRC(" - cache state: %zu prompts, %.3f MiB (limits: %.3f MiB, %zu tokens)\n",
            states.size(), size() / (1024.0 * 1024.0), limit_size / (1024.0 * 1024.0), limit_size > 0 ? 0 : limit_tokens);

    for (const auto & state : states) {
        SRV_TRC("   - prompt %p: %7d tokens, checkpoints: %2zu, %9.3f MiB\n",
                (const void *)&state, state.prompt.n_tokens(), state.prompt.checkpoints.size(), state.size() / (1024.0 * 1024.0));
    }
}
